/**
 * 기본 레시피와 사용자 커스텀 레시피를 합쳐서 냉장고 재료 일치율을 계산하고 정렬합니다.
 * @param {Array<string>} owned - 보유 식재료 목록
 * @param {Array<object>} customRecipes - 사용자가 직접 추가한 레시피 목록
 * @returns {Array<object>} 일치율 순으로 정렬된 레시피 목록
 */
export function recommend(owned = [], customRecipes = []) {
  const allRecipes = [...customRecipes, ...defaultRecipes];

  return allRecipes
    .map((r) => {
      const items = Array.isArray(r.items) ? r.items : [];
      const matched = items.filter((x) => owned.includes(x));
      const missing = items.filter((x) => !owned.includes(x));
      const score = items.length > 0 ? Math.round((matched.length / items.length) * 100) : 0;

      return {
        ...r,
        matched,
        missing,
        score
      };
    })
    .sort((a, b) => b.score - a.score || a.time - b.time);
}
